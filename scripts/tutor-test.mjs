import { chromium } from 'playwright'
import assert from 'node:assert/strict'

const base = process.env.BASE_URL || 'http://127.0.0.1:5173'
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 800 } })
  await page.clock.setFixedTime(new Date('2026-10-24T12:00:00Z'))
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  const requests = []
  await page.route('**/api/health', route => route.fulfill({ json: { status: 'ok', aiConfigured: true } }))
  await page.route('**/api/solve-problem', route => {
    const body = route.request().postDataJSON(); requests.push(body)
    return route.fulfill({ json: { result: requests.length === 1 ? 'First hint: try factoring the quadratic.' : requests.length === 2 ? 'Second hint: look for two numbers whose product is $6$.' : 'Yes, test the pair 2 and 3.' } })
  })
  await page.goto(base)
  await page.getByRole('button', { name: 'Skip', exact: true }).click()
  await page.getByRole('dialog', { name: 'Set up Semester Desk' }).waitFor({ state: 'hidden' })
  await page.goto(`${base}/#/tutor`)
  await page.getByLabel('Learning mode').selectOption('hint')
  await page.getByLabel('Study level').selectOption('School')
  const question = page.getByLabel("What's the problem?")
  await question.pressSequentially('Help me solve x² − 5x + 6 = 0', { delay: 20 })
  await page.getByRole('button', { name: 'Ask Tutor', exact: true }).click()
  await page.getByText('First hint: try factoring the quadratic.', { exact: true }).waitFor()
  assert.equal(requests[0].mode, 'hint'); assert.equal(requests[0].level, 'School')
  await page.getByRole('button', { name: 'Explain the last step more simply.', exact: true }).click()
  await page.getByRole('button', { name: 'Ask follow-up', exact: true }).click()
  await page.getByText('Second hint:', { exact: false }).waitFor()
  assert.deepEqual(requests[1].history.map(m => m.role), ['user', 'assistant'])
  assert.equal(requests[1].history[0].content, 'Help me solve x² − 5x + 6 = 0')
  await page.getByLabel("What's the problem?").fill('Is the pair 2 and 3 correct?')
  await page.getByRole('button', { name: 'Ask follow-up', exact: true }).click()
  await page.getByText('Yes, test the pair 2 and 3.', { exact: true }).waitFor()
  assert.deepEqual(requests[2].history.map(m => m.role), ['user', 'assistant', 'user', 'assistant'])
  await page.reload()
  await page.getByLabel('Saved conversations').selectOption({ label: 'Help me solve x² − 5x + 6 = 0' })
  await page.getByText('First hint: try factoring the quadratic.', { exact: true }).waitFor()
  await page.getByText('Second hint:', { exact: false }).waitFor()
  await page.getByRole('button', { name: 'Save conversation to Notes', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Conversation saved in Notes.' }).waitFor()
  await page.getByRole('link', { name: 'Open Notes', exact: true }).click()
  await page.getByText('Tutor: Help me solve x² − 5x + 6 = 0', { exact: true }).waitFor()
  console.log('PASS Tutor continuous typing, teaching preferences, ordered same-timestamp follow-ups, persistence, and save-to-notes')

  await page.goto(`${base}/#/tutor`)
  await page.getByRole('button', { name: 'New conversation', exact: true }).click()
  await page.unroute('**/api/solve-problem')
  await page.route('**/api/solve-problem', route => route.fulfill({ status: 429, json: { error: 'Gemini quota reached; retry later.' } }))
  await page.getByLabel("What's the problem?").fill('Keep this question after an error')
  await page.getByRole('button', { name: 'Ask Tutor', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: 'Gemini quota reached' }).waitFor()
  assert.equal(await page.getByLabel("What's the problem?").inputValue(), 'Keep this question after an error')
  assert.equal(await page.getByRole('button', { name: 'Ask Tutor', exact: true }).isEnabled(), true)
  console.log('PASS Tutor preserves retryable question on provider quota errors')

  await page.unroute('**/api/solve-problem')
  await page.route('**/api/solve-problem', async route => { await new Promise(resolve => setTimeout(resolve, 3000)); await route.fulfill({ json: { result: 'Late result' } }).catch(() => {}) })
  await page.getByRole('button', { name: 'Ask Tutor', exact: true }).click()
  await page.getByRole('button', { name: 'Stop', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: 'cancelled' }).waitFor()
  assert.equal(await page.getByLabel("What's the problem?").inputValue(), 'Keep this question after an error')
  console.log('PASS Tutor Stop cancels request and preserves the draft')

  await page.goto(`${base}/#/settings`)
  await page.getByLabel('AI server address').fill('https://user:secret@example.com/api?key=bad')
  await page.getByRole('button', { name: 'Save & test connection', exact: true }).click()
  await page.getByText(/without \/api, credentials, or query parameters/).waitFor()
  await page.getByLabel('AI server address').fill('https://demo.example.com')
  await page.getByRole('button', { name: 'Save & test connection', exact: true }).click()
  await page.getByText(/Server connected and a key is configured/).waitFor()
  assert.equal(await page.evaluate(() => localStorage.getItem('semester-desk:ai-server')), 'https://demo.example.com')
  console.log('PASS AI settings validates server origins, saves public URL only, and tests health')
  assert.deepEqual(errors, [])
} finally { await browser.close() }
